DStarDetector::DStarDetector()
{
    m_filterTaps = kGaussianTaps;
    m_inc = kIncUnlock;
}

void DStarDetector::reset()
{
    m_state = State::None;
    m_pattern = 0;
    m_headerBitsCount = 0;
    m_headerBits.fill(0);
    m_lastHeader = {};
    m_dataFrame.fill(0);
    m_dataFrameBits = 0;
    m_dataBits = 0;
    m_events.clear();
    m_headerQueue.clear();
    m_frameQueue.clear();
    m_locked = false;
    m_inc = kIncUnlock;
    m_pll = 0;
    m_prevBit = false;
    m_offset = 0.0F;
    m_accum = 0.0F;
    m_count = 0;
    m_filterBuf.fill(0.0F);
    m_filterPtr = 0;
}

Detection DStarDetector::detect(const IQBlock& block)
{
    bool detected = false;

    for (std::size_t n = 0; n < block.count; ++n) {
        const m17::CD sample{double(block.samples[n].i), double(block.samples[n].q)};
        const double dem = m_fm.process(sample);
        for (const double r : m_resampler.process(dem)) {
            // GMSK matched filter.
            const float val = static_cast<float>(r);
            if (m_locked) {
                m_accum += val;
                m_count++;
                if (m_count >= kDcOffsetCount) {
                    m_accum /= float(kDcOffsetCount);
                    m_offset = m_offset * 0.9F + m_accum * 0.1F;
                    m_accum = 0.0F;
                    m_count = 0;
                }
            }

            m_filterBuf[static_cast<std::size_t>(m_filterPtr)] = val - m_offset;
            m_filterPtr = (m_filterPtr + 1) % 43;
            float out = 0.0F;
            for (int t = 0; t < 43; ++t) {
                int idx = m_filterPtr - 43 + t;
                while (idx < 0) idx += 43;
                out += m_filterTaps[static_cast<std::size_t>(t)] * m_filterBuf[static_cast<std::size_t>(idx)];
            }

            const bool bit = out > 0.0F;
            if (bit != m_prevBit) {
                if (m_pll < kPllMax / 2) m_pll += m_inc;
                else m_pll -= m_inc;
            }
            m_prevBit = bit;
            m_pll += kPllInc;
            if (m_pll >= kPllMax) {
                m_pll -= kPllMax;
                // The GMSK modulator maps bit=1 to a negative baseband, so a
                // negative matched-filter output (out <= 0) means data bit 1.
                if (processBit(!bit))
                    detected = true;
            }
        }
    }

    return {detected, detected ? 1.0F : 0.0F};
}

bool DStarDetector::processBit(bool bit)
{
    m_pattern <<= 1;
    if (bit) m_pattern |= 1;

    if (m_state == State::None) {
        const unsigned int errs = countBits((m_pattern & kFrameSyncMask) ^ kFrameSyncData);
        if (errs <= kFrameSyncErrs) {
            m_locked = true;
            m_inc = kIncLock;
            m_headerBits.fill(0);
            m_headerBitsCount = 0;
            m_state = State::Header;
        }
        return false;
    }

    if (m_state == State::Header) {
        // Header collection (WRITE_BIT2: LSB-first within each byte).
        if (bit)
            m_headerBits[m_headerBitsCount / 8] |= static_cast<std::uint8_t>(1u << (m_headerBitsCount % 8));
        m_headerBitsCount++;

        if (m_headerBitsCount == kFecBits) {
            const bool valid = validateHeader();
            m_headerBitsCount = 0;
            if (valid) {
                m_frameSyncs++;
                // Continue following the DV stream with the PLL still locked,
                // exactly like DStarRepeater after a successful rxHeader().
                m_dataFrame.fill(0);
                m_dataFrameBits = 0;
                m_dataBits = kMaxSyncBits;
                m_state = State::Data;
                pushEvent(DStarRxEvent::Header, &m_lastHeader);
                return true;
            }

            m_locked = false;
            m_inc = kIncUnlock;
            m_state = State::None;
        }
        return false;
    }

    processDataBit(bit);
    return false;
}

void DStarDetector::processDataBit(bool bit)
{
    // WRITE_BIT2: LSB-first within each collected byte.
    if (m_dataFrameBits < kDvFrameBits) {
        if (bit)
            m_dataFrame[m_dataFrameBits / 8] |= static_cast<std::uint8_t>(1u << (m_dataFrameBits % 8));
        m_dataFrameBits++;
    }

    // End-of-transmission marker (fuzzy, as in DStarRepeater).
    unsigned int errs = countBits((m_pattern & kEndSyncMask) ^ kEndSyncData);
    if (errs <= kEndSyncErrs) {
        m_locked = false;
        m_inc = kIncUnlock;
        m_dataFrameBits = 0;
        m_dataBits = 0;
        m_state = State::None;
        pushEvent(DStarRxEvent::Eot);
        return;
    }

    // Fuzzy data-sync detection once a frame is nearly complete.
    bool syncSeen = false;
    if (m_dataFrameBits >= (kDvFrameBits - 3U)) {
        errs = countBits((m_pattern & kDataSyncMask) ^ kDataSyncData);
        if (errs <= kDataSyncErrs) {
            m_dataFrameBits = kDvFrameBits;
            m_dataBits = kMaxSyncBits;
            syncSeen = true;
        }
    }

    // No data sync for too long: treat the stream as lost.
    --m_dataBits;
    if (m_dataBits == 0U) {
        m_locked = false;
        m_inc = kIncUnlock;
        m_dataFrameBits = 0;
        m_state = State::None;
        pushEvent(DStarRxEvent::Lost);
        return;
    }

    // A late data sync may start a few bits before the nominal frame boundary.
    if (m_dataFrameBits == kDvFrameBits && !syncSeen) {
        for (std::uint32_t i = 1; i <= 3; ++i) {
            const std::uint32_t syncMask = kDataSyncMask >> i;
            const std::uint32_t syncData = kDataSyncData >> i;
            errs = countBits((m_pattern & syncMask) ^ syncData);
            if (errs <= kDataSyncErrs) {
                m_dataFrameBits -= i;
                break;
            }
        }
    }

    if (m_dataFrameBits == kDvFrameBits) {
        if (syncSeen) {
            m_dataFrame[9] = kDataSyncBytes[0];
            m_dataFrame[10] = kDataSyncBytes[1];
            m_dataFrame[11] = kDataSyncBytes[2];
        }

        DStarFrame frame;
        frame.bytes = m_dataFrame;
        m_dataFrame.fill(0);
        m_dataFrameBits = 0;
        pushEvent(DStarRxEvent::Data, nullptr, &frame);
    }
}

bool DStarDetector::validateHeader()
{
    std::array<std::uint8_t, 83> in{};
    std::memcpy(in.data(), m_headerBits.data(), kFecBytes);
    for (std::size_t i = 0; i < kFecBytes; ++i)
        in[i] ^= kScrambleRx[i];

    std::array<std::uint8_t, 84> intermediate{};
    std::size_t i = 0;
    while (i < 660) {
        const std::uint8_t d = in[i / 8];
        for (int b = 0; b < 8 && i < 660; ++b) {
            if (d & (1u << b))
                intermediate[kInterleaveRx[i * 2]] |= static_cast<std::uint8_t>(0x80 >> kInterleaveRx[i * 2 + 1]);
            i++;
        }
    }

    m_pathMetric.fill(0);
    m_mar = 0;
    for (int k = 0; k < 660; k += 2) {
        const std::uint8_t byte = intermediate[static_cast<std::size_t>(k / 8)];
        const int d1 = (byte & (0x80 >> (k % 8))) ? 1 : 0;
        const int d0 = (byte & (0x40 >> (k % 8))) ? 1 : 0;
        viterbiDecode(d1, d0);
    }
    traceBack();

    // traceBack() yields 330 bits (41 bytes + 2 tail bits); keep one extra
    // byte so the tail write is well defined.
    std::array<std::uint8_t, 42> header{};
    unsigned int j = 0;
    for (int k = 329; k >= 0; --k) {
        if (m_fecOutput[static_cast<std::size_t>(k / 8)] & kMask1[static_cast<std::size_t>(k % 8)])
            header[j / 8] |= static_cast<std::uint8_t>(1u << (j % 8));
        j++;
    }

    std::uint16_t crc = 0xFFFF;
    for (int k = 0; k < 39; ++k)
        crc = static_cast<std::uint16_t>((crc >> 8) ^ kCcittTable[(crc & 0xFF) ^ header[static_cast<std::size_t>(k)]]);
    crc = static_cast<std::uint16_t>(~crc);
    const bool valid = static_cast<std::uint8_t>(crc) == header[39] &&
                       static_cast<std::uint8_t>(crc >> 8) == header[40];
    if (valid) {
        std::copy_n(header.begin(), m_lastHeader.bytes.size(), m_lastHeader.bytes.begin());
    }
    return valid;
}

unsigned int DStarDetector::countBits(std::uint32_t value) const
{
    unsigned int count = 0;
    for (int i = 0; i < 8; ++i)
        count += kNibbleBits[(value >> (i * 4)) & 0x0F];
    return count;
}

void DStarDetector::viterbiDecode(int data1, int data0)
{
    std::array<int, 8> metric{};
    metric[0] = (data1 ^ 0) + (data0 ^ 0);
    metric[1] = (data1 ^ 1) + (data0 ^ 1);
    metric[2] = (data1 ^ 1) + (data0 ^ 0);
    metric[3] = (data1 ^ 0) + (data0 ^ 1);
    metric[4] = (data1 ^ 1) + (data0 ^ 1);
    metric[5] = (data1 ^ 0) + (data0 ^ 0);
    metric[6] = (data1 ^ 0) + (data0 ^ 1);
    metric[7] = (data1 ^ 1) + (data0 ^ 0);
    acs(metric);
}

void DStarDetector::acs(const std::array<int, 8>& metric)
{
    std::array<int, 4> temp{};
    const unsigned int j = m_mar / 8;
    const unsigned int k = m_mar % 8;

    const int m1 = metric[0] + m_pathMetric[0];
    const int m2 = metric[4] + m_pathMetric[2];
    temp[0] = m1 < m2 ? m1 : m2;
    if (m1 < m2) m_pathMemory0[j] &= kMask0[k]; else m_pathMemory0[j] |= kMask1[k];

    const int m3 = metric[1] + m_pathMetric[0];
    const int m4 = metric[5] + m_pathMetric[2];
    temp[1] = m3 < m4 ? m3 : m4;
    if (m3 < m4) m_pathMemory1[j] &= kMask0[k]; else m_pathMemory1[j] |= kMask1[k];

    const int m5 = metric[2] + m_pathMetric[1];
    const int m6 = metric[6] + m_pathMetric[3];
    temp[2] = m5 < m6 ? m5 : m6;
    if (m5 < m6) m_pathMemory2[j] &= kMask0[k]; else m_pathMemory2[j] |= kMask1[k];

    const int m7 = metric[3] + m_pathMetric[1];
    const int m8 = metric[7] + m_pathMetric[3];
    temp[3] = m7 < m8 ? m7 : m8;
    if (m7 < m8) m_pathMemory3[j] &= kMask0[k]; else m_pathMemory3[j] |= kMask1[k];

    m_pathMetric = temp;
    m_mar++;
}

void DStarDetector::traceBack()
{
    unsigned int j = 0;
    unsigned int k = 0;
    for (int i = 329; i >= 0; --i) {
        switch (j) {
            case 0:
                if ((m_pathMemory0[static_cast<std::size_t>(i / 8)] & kMask1[static_cast<std::size_t>(i % 8)]) == 0) j = 0; else j = 2;
                m_fecOutput[k / 8] = (m_fecOutput[k / 8] & ~kMask1[k % 8]);  // write 0
                k++;
                break;
            case 1:
                if ((m_pathMemory1[static_cast<std::size_t>(i / 8)] & kMask1[static_cast<std::size_t>(i % 8)]) == 0) j = 0; else j = 2;
                m_fecOutput[k / 8] |= kMask1[k % 8];  // write 1
                k++;
                break;
            case 2:
                if ((m_pathMemory2[static_cast<std::size_t>(i / 8)] & kMask1[static_cast<std::size_t>(i % 8)]) == 0) j = 1; else j = 3;
                m_fecOutput[k / 8] = (m_fecOutput[k / 8] & ~kMask1[k % 8]);
                k++;
                break;
            case 3:
                if ((m_pathMemory3[static_cast<std::size_t>(i / 8)] & kMask1[static_cast<std::size_t>(i % 8)]) == 0) j = 1; else j = 3;
                m_fecOutput[k / 8] |= kMask1[k % 8];
                k++;
                break;
        }
    }
}

bool DStarDetector::feedBit(bool bit)
{
    return processBit(bit);
}

void DStarDetector::pushEvent(DStarRxEvent event, const DStarHeader* header,
                              const DStarFrame* frame)
{
    m_events.push_back(event);
    if (header)
        m_headerQueue.push_back(*header);
    if (frame)
        m_frameQueue.push_back(*frame);
}

bool DStarDetector::nextEvent(DStarRxEvent& event, DStarHeader* header,
                              DStarFrame* frame)
{
    if (m_events.empty())
        return false;

    event = m_events.front();
    m_events.pop_front();

    if (header && event == DStarRxEvent::Header && !m_headerQueue.empty()) {
        *header = m_headerQueue.front();
        m_headerQueue.pop_front();
    }
    if (frame && event == DStarRxEvent::Data && !m_frameQueue.empty()) {
        *frame = m_frameQueue.front();
        m_frameQueue.pop_front();
    }
    return true;
}

