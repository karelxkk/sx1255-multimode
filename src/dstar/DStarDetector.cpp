std::uint16_t dstarHeaderCrc(const std::uint8_t* data, std::size_t length)
{
    std::uint16_t crc = 0xFFFF;
    for (std::size_t i = 0; i < length; ++i)
        crc = static_cast<std::uint16_t>((crc >> 8) ^ kCcittTable[(crc & 0xFF) ^ data[i]]);
    return static_cast<std::uint16_t>(~crc);
}

std::array<std::uint8_t, 83> dstarFecEncode(const std::array<std::uint8_t, 41>& header)
{
    std::array<std::uint8_t, 84> intermediate{};
    std::array<std::uint8_t, 83> out{};
    // txHeader() in DStarRepeater convolves 42 bytes; the 42nd byte's first
    // two bits survive into the on-air block and are ignored by the CRC, so a
    // deterministic zero padding reproduces the same wire format.
    std::array<std::uint8_t, 42> in{};
    std::copy(header.begin(), header.end(), in.begin());

    // Rate-1/2 convolutional encode (42 bytes -> 660 coded bits).
    std::uint8_t d1 = 0, d2 = 0;
    unsigned int k = 0;
    for (int i = 0; i < 42; ++i) {
        for (int j = 0; j < 8; ++j) {
            const std::uint8_t mask = static_cast<std::uint8_t>(1u << j);
            const std::uint8_t d = (in[static_cast<std::size_t>(i)] & mask) ? 1 : 0;
            const std::uint8_t g0 = (d + d2) % 2;
            const std::uint8_t g1 = (d + d1 + d2) % 2;
            d2 = d1;
            d1 = d;
            if (g1) intermediate[k / 8] |= static_cast<std::uint8_t>(0x80 >> (k % 8));
            k++;
            if (g0) intermediate[k / 8] |= static_cast<std::uint8_t>(0x80 >> (k % 8));
            k++;
        }
    }

    // Interleave (660 bits).
    std::size_t i = 0;
    while (i < 660) {
        const std::uint8_t d = intermediate[i / 8];
        for (int b = 0; b < 8 && i < 660; ++b) {
            if (d & (0x80 >> b))
                out[kInterleaveTx[i * 2]] |= static_cast<std::uint8_t>(0x01u << kInterleaveTx[i * 2 + 1]);
            i++;
        }
    }

    // Scramble.
    for (std::size_t n = 0; n < 83; ++n)
        out[n] ^= kScrambleTx[n];
    return out;
}

